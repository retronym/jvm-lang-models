#!/usr/bin/env python3
"""Write the oracle's verdicts over Track T's first space as Lean data
(packages/scala-types/ScalaTypes/PathsData.lean), for the theorems of ScalaTypes/PathsOracle.lean.

    soundness_lean.py LEDGER OUT.lean      (LEDGER from soundness.py --json over `lake exe soundspace`)

Per setting, two lists over the space in order: the compiler's verdict (0 accepted, then the first
error by kind, as `Scala.Paths.Verdict`) and the run's (0 not run, 1 ok, 2 ClassCastException,
3 expected, 4 other).
"""
import json, sys

SETTINGS = [('s212', '2.12.21'), ('s213', '2.13.18'), ('s3', '3.9.0'), ('s3future', '3.9.0 -source future'),
            ('s3nulls', '3.9.0 -Yexplicit-nulls')]
KINDS = ['accept', 'wellFormed', 'nullPath', 'instantiate', 'mismatch', 'notPath', 'override']


def kind(r):
    if r['verdict'] != 'rejected':
        return 'accept'
    d = r['detail']
    if 'Found: Null' in d: return 'nullPath'
    if 'type mismatch' in d or d.startswith('Found:'): return 'mismatch'
    if 'not a legal path' in d: return 'notPath'
    if 'cannot be instantiated' in d: return 'instantiate'
    if 'incompatible type' in d: return 'override'
    if 'does not conform to upper bound' in d: return 'wellFormed'
    raise SystemExit(f'unclassified error: {r}')


RUN = {'rejected': 0, 'ok': 1, 'cce': 2, 'expected': 3, 'other': 4}


def main(ledger, out):
    rows = {}
    for r in map(json.loads, open(ledger)):
        rows[(r['setting'], int(r['case'][1:]))] = r
    n = 1 + max(i for _, i in rows)
    lines = ['/-! Generated by `packages/scala/probes/soundness_lean.py` from the oracle\'s ledger over',
             '`Scala.Paths.space`: per setting, the compiler\'s verdict (`Verdict`, by index) and the run\'s',
             '(0 not run, 1 ok, 2 `ClassCastException`, 3 expected, 4 other). Do not edit. -/', '',
             'namespace Scala.Paths.Data', '']
    for name, label in SETTINGS:
        ks = [KINDS.index(kind(rows[(label, i)])) for i in range(n)]
        rs = [RUN[rows[(label, i)]['verdict']] for i in range(n)]
        lines.append(f'def compiled_{name} : List Nat := {ks}')
        lines.append(f'def ran_{name} : List Nat := {rs}')
        lines.append('')
    lines.append('end Scala.Paths.Data')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:])
