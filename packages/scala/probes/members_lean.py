#!/usr/bin/env python3
"""Write the oracle's results over the membership space as Lean data
(packages/scala/Scala/RefchecksData.lean), for the theorems of packages/scala/Scala/Refchecks.lean.

    members_lean.py OUT OUT.lean      (OUT from members.py over `Members.membersSpace`)

Per dialect: the programs the compiler accepted (indices into `Members.membersSpace`), and, for each
accepted program that `Members` also accepted, which owner's `m` HotSpot ran for each concrete class
(`!AbstractMethodError` and the like when `new C().m` threw).
"""
import json, os, sys

DIALECTS = [('s212', '2.12'), ('s213', '2.13'), ('s3', '3')]


def lean_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main(out, dest):
    lines = ['/-! Generated by `packages/scala/probes/members_lean.py` from `members.py`\'s results over',
             '`Scala.Members.membersSpace` (scalac 2.12.21, 2.13.18, dotc 3.9.0; each accepted program run on',
             'HotSpot): per dialect, the indices of the programs the compiler accepted, and for each one that ran,',
             'the owner whose `m` ran per concrete class, or the exception. Do not edit. -/', '',
             'namespace Scala.Refchecks.Data', '']
    for name, tag in DIALECTS:
        d = json.load(open(os.path.join(out, f'members-actual-{tag}.json')))
        idx = sorted(int(p[1:]) for p in d)
        acc = [i for i in idx if not d[f'q{i}']['errs']]
        ran = [(i, sorted(d[f'q{i}']['runs'].items())) for i in idx if d[f'q{i}']['runs']]
        lines.append(f'def accepted_{name} : List Nat := {acc}')
        lines.append(f'def ran_{name} : List (Nat × List (String × String)) := [' + ', '.join(
            f'({i}, [' + ', '.join(f'({lean_str(c)}, {lean_str(o)})' for c, o in rs) + '])' for i, rs in ran) + ']')
        lines.append('')
    lines.append('end Scala.Refchecks.Data')
    open(dest, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:])
