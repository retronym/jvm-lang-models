"""Writes `docs/stats.md`: per package, its Lean files, lines, theorems and checked examples.

These numbers used to be counted by hand and went stale within days. Run this after changing the
Lean; CI runs it with `--check`, which fails if the committed file differs from what it would write.

Counted over each package's `.lean` files outside `.lake/`: lines with `wc -l` semantics,
theorems as `theorem` and `lemma` declarations, examples as `example`s (not the `Spec` modules'
`example := @name` checks).

Usage: python3 -I scripts/model_stats.py [--check]
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'stats.md')
THEOREM = re.compile(r'^\s*(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable)\s+)*(?:theorem|lemma)\s', re.M)
EXAMPLE = re.compile(r'^\s*example\b(?!\s*:=\s*@)', re.M)  # not the `Spec` modules' name checks

ORDER = ['query', 'jvm', 'java', 'scala-types', 'scala', 'intellij', 'inc-comp', 'zinc', 'mima',
         'links', 'harness']


def count(pkg):
    files = [f for f in glob.glob(os.path.join(ROOT, 'packages', pkg, '**', '*.lean'), recursive=True)
             if '/.lake/' not in f]
    lines = theorems = examples = 0
    for f in files:
        text = open(f, encoding='utf-8').read()
        lines += text.count('\n')
        theorems += len(THEOREM.findall(text))
        examples += len(EXAMPLE.findall(text))
    return len(files), lines, theorems, examples


def render():
    pkgs = [p for p in ORDER if os.path.isdir(os.path.join(ROOT, 'packages', p))]
    pkgs += sorted(p for p in os.listdir(os.path.join(ROOT, 'packages')) if p not in pkgs)
    rows = [(p,) + count(p) for p in pkgs]
    total = tuple(sum(r[i] for r in rows) for i in range(1, 5))
    out = ['# Model size, per package', '',
           'Generated by [`scripts/model_stats.py`](../scripts/model_stats.py); do not edit. CI fails if it is out of date.', '',
           '| package | Lean files | lines | theorems | checked examples |',
           '|---|---|---|---|---|']
    for p, f, l, t, e in rows:
        out.append(f'| [`{p}`](../packages/{p}/README.md) | {f} | {l:,} | {t:,} | {e:,} |')
    out.append(f'| **total** | **{total[0]}** | **{total[1]:,}** | **{total[2]:,}** | **{total[3]:,}** |')
    return '\n'.join(out) + '\n'


def main():
    text = render()
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old != text:
            print('docs/stats.md is out of date: run python3 -I scripts/model_stats.py')
            sys.exit(1)
        print('docs/stats.md is current')
        return
    open(OUT, 'w', encoding='utf-8').write(text)
    print(text)


if __name__ == '__main__':
    main()
